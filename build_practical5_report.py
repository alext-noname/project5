NS_A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
with ZipFile(OUTPUT, "r") as source:
    entries = {name: source.read(name) for name in source.namelist()}

for i in range(1, 9):
    name = f"ppt/slides/slide{i}.xml"
    root = ET.fromstring(entries[name])
    for text_node in root.findall(".//" + NS_A + "t"):
        original = text_node.text or ""
        if original in replacements:
            text_node.text = replacements[original]
    entries[name] = ET.tostring(root, encoding="utf-8", xml_declaration=True)

with ZipFile(OUTPUT, "w") as target:
    for name, content in entries.items():
        target.writestr(name, content)

print(OUTPUT)
